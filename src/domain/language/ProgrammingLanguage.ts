import type { NameStyle } from "../pack/naming/NameStyle";

export const PROGRAMMING_LANGUAGES = ["typescript", "python", "ruby", "ruby-dry"] as const;
export type ProgrammingLanguageId = (typeof PROGRAMMING_LANGUAGES)[number];

export const DEFAULT_PROGRAMMING_LANGUAGE: ProgrammingLanguageId = "typescript";

/**
 * What the pack validator needs to know about a language to guarantee that generated identifiers
 * are legal there. Template details live in the generation layer.
 */
export interface LanguageNamingProfile {
  readonly typeStyle: NameStyle;
  readonly memberStyle: NameStyle;
  /** Words that cannot be used as identifiers, after conversion to the language's style. */
  readonly reservedWords: ReadonlySet<string>;
  /** Names of standard-library or framework types that a generated type must not shadow. */
  readonly reservedTypeNames: ReadonlySet<string>;
}

